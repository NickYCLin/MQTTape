export function isLanguage(value: unknown): value is Language {
  return typeof value === 'string' && supportedLanguages.includes(value as Language)
}

export function readLanguage(storage: Pick<Storage, 'getItem'>): Language {
  try {
    const stored = storage.getItem(LANGUAGE_STORAGE_KEY)
    return isLanguage(stored) ? stored : 'en'
  } catch {
    return 'en'
  }
}

export function writeLanguage(
  storage: Pick<Storage, 'setItem'>,
  language: Language
): void {
  try {
    storage.setItem(LANGUAGE_STORAGE_KEY, language)
  } catch {
    // The current session can still switch languages when storage is unavailable.
  }
}

export function translate(
  language: Language,
  key: TranslationKey,
  parameters: TranslationParameters = {}
): string {
  return Object.entries(parameters).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    translations[language][key]
  )
}

export function translateKnownMessage(language: Language, message: string): string {
  if (language === 'en') return message

  const key = knownMessageKeys[message]
  if (key) return translate(language, key)

  const presetLimit = message.match(/^Replay presets are limited to (\d+)\.$/)
  if (presetLimit) return translate(language, 'errors.presetLimit', { count: presetLimit[1] })

  const presetNameLength = message.match(/^Preset name must be (\d+) characters or fewer\.$/)
  if (presetNameLength) {
    return translate(language, 'errors.presetNameLength', { count: presetNameLength[1] })
  }

  const presetDuplicate = message.match(/^A replay preset named “(.+)” already exists\.$/)
  if (presetDuplicate) {
    return translate(language, 'errors.presetDuplicate', { name: presetDuplicate[1] })
  }

  const appliedPreset = message.match(/^Applied “(.+)”\.$/)
  if (appliedPreset) return translate(language, 'replay.appliedPreset', { name: appliedPreset[1] })

  const savedPreset = message.match(/^Saved “(.+)” locally\.$/)
  if (savedPreset) return translate(language, 'replay.savedPresetFeedback', { name: savedPreset[1] })

  const deletedPreset = message.match(/^Deleted “(.+)”\.$/)
  if (deletedPreset) return translate(language, 'replay.deletedPreset', { name: deletedPreset[1] })

  const invalidReplayTopic = message.match(/^Invalid replay topic "(.+)": (.+)$/)
  if (invalidReplayTopic) {
    return `${translate(language, 'replay.invalidTopic', { topic: invalidReplayTopic[1] })} ${translateKnownMessage(language, invalidReplayTopic[2])}`
  }

  return message
}
